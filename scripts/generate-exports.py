#!/usr/bin/env python3
"""Regenerate backend/__init__.py's lazy export map.

    python3 scripts/generate-exports.py           # rewrite
    python3 scripts/generate-exports.py --check   # fail if out of date

Why this exists
---------------
``backend/app.py`` does ``from backend import *`` and then references ~276
route handlers by bare name. The export map in ``backend/__init__.py`` is what
makes those names resolve. When the map was hand-built it silently omitted 170
of them, and the failure was a ``NameError`` raised deep inside
``create_app()`` at start-up -- not an ImportError -- so it was invisible until
a container actually ran.

So the map is generated from the source of truth (the modules themselves)
rather than maintained by hand.

Collision policy
----------------
A few names are defined in more than one module. Modules are scanned in sorted
filename order and the last wins. That is arbitrary but deterministic; run this
twice and you get the same answer. ``__getattr__`` names the chosen module in
its error message so a wrong winner is easy to trace back here.
"""

import argparse
import ast
import pathlib
import sys
from collections import OrderedDict

REPO = pathlib.Path(__file__).resolve().parent.parent
BACKEND = REPO / "backend"
INIT = BACKEND / "__init__.py"

HEADER = '''"""RMM backend package.

Re-exports the application's public API so ``from backend import *`` works.

Why this is lazy
----------------
An eager barrel here -- a module-level ``from .x import *`` for every
feature module -- meant that importing *any* submodule pulled in the whole
dependency tree. That defeated modules such as ``backend.roles``, which
deliberately imports nothing from Flask, MySQL or a scheduler so both
process roles can read it before the application object exists. The practical
symptom was that the unit tests could not even collect.

Resolving on first use (PEP 562) keeps ``backend.X`` and
``from backend import X`` working without importing every feature module when
you only want, say, ``backend.roles``.

Caveat worth knowing: ``backend/app.py`` does ``from backend import *``, and
CPython resolves *every* name in ``__all__`` for a star-import. So for the
application itself the map is effectively eager -- all ~135 modules are
imported during start-up. That is why this file is generated rather than
hand-written, and why anything that cannot be imported (an entry point, a
non-module config script, a module with a missing dependency) must be excluded
here rather than discovered at runtime.

Do not hand-edit ``_EXPORTS``
-----------------------------
It is generated by scanning every module (and subpackage) under backend/ for
its public top-level names, so the map is a SUPERSET of anything the old
barrel exported. A previous, hand-built map silently omitted 170 of the 278
names ``backend/app.py`` pulls in via ``from backend import *``, which surfaced
as a NameError inside ``create_app()`` at start-up rather than as an import
error. Regenerate it with:

    python3 scripts/generate-exports.py

Name collisions
---------------
A few names are defined in more than one module. Modules are scanned in sorted
filename order and the last one wins, which is arbitrary but deterministic and
reproducible. ``__getattr__`` reports the chosen module in its error message so
a wrong winner is easy to trace.
"""'''

TAIL = '''

def __getattr__(name):
    """Resolve a re-exported name on first use (PEP 562)."""
    module = _EXPORTS.get(name)
    if module is None:
        raise AttributeError(
            f"module {__name__!r} has no attribute {name!r}. "
            f"It is not one of the {len(_EXPORTS)} names this package re-exports."
        )
    value = getattr(importlib.import_module(module), name)
    globals()[name] = value  # cache, so later lookups skip __getattr__
    return value


def __dir__():
    return sorted(set(globals()) | set(_EXPORTS))


__all__ = sorted(_EXPORTS)
'''


def public_names(path: pathlib.Path):
    """Public top-level names defined or bound by a module."""
    try:
        tree = ast.parse(path.read_text(encoding="utf-8", errors="replace"))
    except SyntaxError as exc:
        print(f"  skipping {path.name}: {exc}", file=sys.stderr)
        return set()
    names = set()
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            if not node.name.startswith("_"):
                names.add(node.name)
        elif isinstance(node, ast.Assign):
            for t in node.targets:
                if isinstance(t, ast.Name) and not t.id.startswith("_"):
                    names.add(t.id)
        elif isinstance(node, ast.AnnAssign):
            if isinstance(node.target, ast.Name) and not node.target.id.startswith("_"):
                names.add(node.target.id)
    return names


# Modules that exist in the tree but are NOT importable members of the
# package, and so must never appear in the export map.
def _is_importable_module(path: pathlib.Path) -> bool:
    """A module is importable as dotted-path parts only if each part is a
    valid Python identifier.

    backend/gunicorn.conf.py is the case in point: Gunicorn loads it with
    --config, and its stem "gunicorn.conf" is not an identifier, so
    importlib.import_module("backend.gunicorn") raises ModuleNotFoundError.
    Because app.py does `from backend import *`, listing it broke the whole
    API at import time.
    """
    if path.stem == "__init__":
        return False
    # A dotted stem such as "gunicorn.conf" is NOT a single
    # importable module name: importlib.import_module
    # ("backend.gunicorn") cannot resolve it, because the package
    # exposes no `gunicorn` submodule. Require a plain identifier.
    if "." in path.stem:
        return False
    if not path.stem.isidentifier():
        return False
    return True


# Process entry points. These are not library modules: they are what Gunicorn,
# the worker container and the health probe execute, and each one boots the
# application. If the package's export namespace pointed at them, then
# `from backend import *` -- which backend/app.py itself does -- would import
# them mid-initialisation.
#
# backend/wsgi.py is the concrete failure: it does `from backend.app import app`
# at module level, so resolving any name that mapped to it while app.py was
# still executing raised
#   ImportError: cannot import name 'app' from partially initialized module
# 'backend.app' (most likely due to a circular import)
# and took the whole API down at start-up.
# Build-time tooling that is not part of the running application. It lives in
# backend/ so the image contains it, but it must not be pulled into
# `from backend import *` and executed on every import.
BUILD_TOOLING = {"check_python_m_entrypoints", "check_gunicorn_config"}

ENTRY_POINTS = {"app", "wsgi", "worker", "worker_healthcheck"}


def _is_entry_point(path: pathlib.Path) -> bool:
    """True for process entry points, which must stay out of the namespace."""
    if path.stem in ENTRY_POINTS or path.stem in BUILD_TOOLING:
        return True
    # Belt and braces: anything importing backend.app or backend.wsgi at import
    # time is an entry point by definition, whatever it is named.
    class V(ast.NodeVisitor):
        found = False

        def visit_FunctionDef(self, n):      # bodies do not run on import
            pass

        def visit_AsyncFunctionDef(self, n):
            pass

        def visit_ClassDef(self, n):
            pass

        def visit_ImportFrom(self, n):
            if (n.module or "") in ("backend.app", "backend.wsgi"):
                self.found = True
            self.generic_visit(n)

        def visit_Import(self, n):
            for a in n.names:
                if a.name in ("backend.app", "backend.wsgi"):
                    self.found = True

    try:
        tree = ast.parse(path.read_text(encoding="utf-8", errors="replace"))
    except SyntaxError:
        return False
    v = V()
    v.visit(tree)
    return v.found


def collect():
    candidates = [
        (p, f"backend.{p.stem}")
        for p in sorted(BACKEND.glob("*.py"))
        if _is_importable_module(p) and not _is_entry_point(p)
    ]
    # Subpackages count too: backend/manual_platform/__init__.py does
    # `from .api import *`, so app.py reaches further names through it.
    for pkg in sorted(BACKEND.iterdir()):
        if not pkg.is_dir() or not (pkg / "__init__.py").exists():
            continue
        if not all(p.isidentifier() for p in pkg.name.split(".")):
            continue
        for sub in sorted(pkg.glob("*.py")):
            if _is_importable_module(sub) and not _is_entry_point(sub):
                candidates.append((sub, f"backend.{pkg.name}.{sub.stem}"))

    exports = OrderedDict()
    collisions = OrderedDict()
    for path, mod in candidates:
        for name in sorted(public_names(path)):
            if name in exports and exports[name] != mod:
                collisions.setdefault(name, [exports[name]]).append(mod)
            exports[name] = mod
    return exports, collisions


def render(exports):
    width = max((len(k) for k in exports), default=1)
    out = [HEADER, "", "import importlib", "",
           "#: Public name -> module that defines it.", "_EXPORTS = {"]
    for k, v in sorted(exports.items()):
        pad = " " * max(1, width - len(k) + 2)
        out.append(f'    "{k}":{pad}"{v}",')
    out.append("}")
    return "\n".join(out) + "\n" + TAIL


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true",
                    help="exit non-zero if backend/__init__.py is out of date")
    args = ap.parse_args()

    exports, collisions = collect()
    excluded = [p for p in sorted(BACKEND.rglob("*.py"))
                if "__pycache__" not in p.parts
                and (not _is_importable_module(p) or _is_entry_point(p))]
    for p in excluded:
        why = "not an importable module" if not _is_importable_module(p) else "process entry point"
        print(f"  excluded ({why}): {p.relative_to(REPO)}")
    print(f"modules scanned : {len(list(BACKEND.glob('*.py'))) - 1} + subpackages")
    print(f"names exported  : {len(exports)}")
    print(f"collisions      : {len(collisions)} (last module in sorted order wins)")

    # Every mapped module must be a real dotted path with identifier parts, or
    # `from backend import *` will raise ModuleNotFoundError at start-up. This
    # is cheap and catches the class of bug where a non-module file (a config
    # script, a launcher) is globbed in.
    broken = sorted({v for v in exports.values()
                     if not all(p.isidentifier() for p in v.split("."))})
    if broken:
        print("::error::export map contains non-importable module paths:")
        for b in broken:
            print(f"  {b}")
        return 1

    rendered = render(exports)

    if args.check:
        current = INIT.read_text(encoding="utf-8")
        if current != rendered:
            print("::error::backend/__init__.py is out of date; run "
                  "python3 scripts/generate-exports.py")
            return 1
        print("backend/__init__.py is up to date")
        return 0

    INIT.write_text(rendered, encoding="utf-8")
    print(f"wrote {INIT.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
