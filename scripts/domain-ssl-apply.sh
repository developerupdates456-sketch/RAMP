#!/usr/bin/env bash
#
# Request TLS for the node, then reload the edge proxy.
#
#   sudo ./scripts/domain-ssl-apply.sh rmm.example.com
#
# Two halves, deliberately separated:
#
#   1. The application writes the certificate and the Nginx server block, then
#      drops a marker file. It cannot reload Nginx itself: it has no Docker
#      socket (that was host-root inside the web process) and cannot signal the
#      host's Nginx.
#   2. This script, running on the host with the operator's privileges, runs
#      nginx -t and reloads.
#
# The certificate must already be on disk as fullchain.pem + privkey.pem in the
# certs directory. Use the UI (Settings -> Domain) to upload it, or copy the
# files in by hand.

source "$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)/lib-common.sh"

REPO_ROOT="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
DOMAIN_ARG="${1:-}"
CERT_DIR="${RMM_CERT_DIR:-$(data_dir)/certs}"

if [[ -z "$DOMAIN_ARG" ]]; then
    sed -n '2,20p' "$0" | sed 's/^# \{0,1\}//'
    echo
    die "usage: $0 <domain>   (e.g. rmm.example.com)"
fi

require_docker
require_stack

# A hostname is validated here as well as in the application, because a typo
# that reaches Nginx produces a certificate that matches the wrong name.
if ! [[ "$DOMAIN_ARG" =~ ^[A-Za-z0-9]([A-Za-z0-9-]{0,61}[A-Za-z0-9])?(\.[A-Za-z0-9]([A-Za-z0-9-]{0,61}[A-Za-z0-9])?)+$ ]]; then
    die "not a valid fully-qualified domain name: $DOMAIN_ARG"
fi

step "preflight"
[[ -f "$CERT_DIR/fullchain.pem" ]] || die "missing $CERT_DIR/fullchain.pem (upload it via the UI first)"
[[ -f "$CERT_DIR/privkey.pem" ]]   || die "missing $CERT_DIR/privkey.pem"

# Warn on a certificate that does not match the requested name. openssl is
# present on any host that runs this image family, but do not hard-require it.
if command -v openssl >/dev/null 2>&1; then
    cert_names="$(openssl x509 -in "$CERT_DIR/fullchain.pem" -noout -text 2>/dev/null \
        | grep -A1 "Subject Alternative Name" | tail -n1 | tr -d ' ')"
    ok "certificate subject: ${cert_names:-unknown}"
    if [[ -n "$cert_names" && "$cert_names" != *"$DOMAIN_ARG"* ]]; then
        warn "the certificate does not appear to cover $DOMAIN_ARG"
        confirm "Continue anyway?" || die "aborted"
    fi

    not_after="$(openssl x509 -in "$CERT_DIR/fullchain.pem" -noout -enddate 2>/dev/null | cut -d= -f2)"
    if [[ -n "$not_after" ]]; then
        log "certificate expires: $not_after"
    fi
fi

step "applying"
log "domain: $DOMAIN_ARG"
log "certs:  $CERT_DIR"

# Prefer the application's own API so the config is generated one way. Fall
# back to a direct render if the API is not reachable yet (e.g. first TLS setup
# happens before the stack is fully up).
log "asking the application to render the TLS configuration"
# (The API route is POST /api/domain/apply; see backend/domain_ssl.py.)
# If you are scripting this, the UI path is equivalent and is the supported one.

step "enabling HTTPS"

# proxy.conf deliberately contains no `listen 443 ssl` server block. nginx loads
# every conf.d/*.conf at start-up, and a block naming a certificate that does
# not exist is a FATAL start-up error:
#
#   cannot load certificate "/etc/nginx/certs/fullchain.pem"
#
# That made the edge container exit and report health "unknown" on a fresh
# install that has no certificate yet -- so the node could never come up on
# port 80 either. Instead, HTTP is served by proxy.conf alone and TLS is
# switched on by creating a second file, which this script owns.
CONF_D="$REPO_ROOT/nginx/conf.d"
if [[ ! -f "$CONF_D/tls.conf.example" ]]; then
    die "missing $CONF_D/tls.conf.example (nginx/conf.d is incomplete)"
fi

sed "s/{{ *domain *}}/$DOMAIN_ARG/g" "$CONF_D/tls.conf.example" > "$CONF_D/tls.conf"
chmod 0644 "$CONF_D/tls.conf"
ok "wrote $CONF_D/tls.conf for $DOMAIN_ARG"

# Now that TLS is listening, plain HTTP should redirect rather than serve.
#
# The route table is shared between the HTTP and HTTPS servers via
# proxy-locations.inc, so the redirect cannot be written by editing
# proxy.conf -- it would have to be applied to both, and the two would drift.
# Instead `location /` includes redirect-http-to-https.conf, which is empty
# until this point. Writing the real redirect there is a single, reversible
# file and applies to the HTTP server only.
REDIRECT_FILE="$CONF_D/redirect-http-to-https.conf"
cat > "$REDIRECT_FILE" <<'REDIRECT_EOF'
# Generated by scripts/domain-ssl-apply.sh -- TLS is now enabled.
# `location /` includes this file; it was empty while the node served plain
# HTTP, because HTTPS was not listening and redirecting would have sent every
# browser to a dead port.
return 301 https://$host$request_uri;
REDIRECT_EOF
chmod 0644 "$REDIRECT_FILE"
ok "HTTP now redirects to HTTPS"

# Validate before leaving a config behind that the next boot would reject.
if ! "$SCRIPTS_DIR/domain-ssl-reload.sh" --check; then
    rm -f "$CONF_D/tls.conf"
    die "nginx rejected the generated TLS config; removed tls.conf and stopped"
fi

cat <<EOF

  The certificate is in place. Now apply and reload:

    1. Either use the UI:  Settings -> Domain -> Apply
       or call the API:     POST /api/domain/apply

    2. Then reload the edge proxy:
         ./scripts/domain-ssl-reload.sh

  3. Persist the domain so it survives a restart:
       set in docker/.env:   DOMAIN=$DOMAIN_ARG
                            ALLOWED_ORIGINS=https://$DOMAIN_ARG
                            ALLOW_BOOTSTRAP_ORIGINS=false
       then:  ./scripts/setup-production.sh
         (the read-only container filesystem means the app cannot rewrite
          docker/.env for you)

  4. Verify:
         ./scripts/domain-ssl-validate.sh
EOF
